// Generates the agent's knowledge from data/portfolio.ts, data/portfolio-ar.ts, data/ui.ts, and the CV
// library, so the site stays the single source of truth. Output is a TypeScript module the Worker bundles.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { cvEntries, cvRecognition, cvSkills, cvSummaries, cvTeaching, cvTraining } from "../data/cv";
import { getContent } from "../data/i18n";
import { buildKnowledge } from "../lib/agent/knowledge";

const OUTPUT = path.resolve("worker/src/generated/knowledge.ts");

// What the model sees when it picks CV lines: IDs, the section they belong to, and the approved text.
function cvCatalog() {
  const line = (kind: string, item: { id: string; text: string; approved: boolean }) => (item.approved ? `- ${item.id} [${kind}] ${item.text}` : null);
  const rows = [
    ...Object.values(cvSummaries).map((item) => line("summary", item)),
    ...cvSkills.map((item) => line("skill", item)),
    ...cvEntries.filter((entry) => entry.approved).flatMap((entry) => [
      `- ${entry.id} [${entry.section} entry] ${entry.title}, ${entry.meta}`,
      ...entry.bullets.map((bullet) => (bullet.approved ? `  - ${bullet.id} [bullet of ${entry.id}] ${bullet.text}` : null))
    ]),
    ...cvRecognition.map((item) => line("recognition", item)),
    ...cvTraining.map((item) => line("training", item)),
    ...cvTeaching.map((item) => line("teaching", item))
  ];
  return rows.filter(Boolean).join("\n");
}

async function main() {
  const bundle = buildKnowledge(getContent("en"), getContent("ar"));
  const catalog = cvCatalog();
  const version = createHash("sha256").update(bundle.text.en).update(bundle.text.ar).update(catalog).digest("hex").slice(0, 10);
  const source = `// Generated by scripts/build-knowledge.ts from the site's data files. Do not edit by hand.
// Rebuild with: npm run knowledge
import type { KnowledgeBundle } from "../../../lib/agent/types";

export const KNOWLEDGE_VERSION = ${JSON.stringify(version)};

export const KNOWLEDGE: KnowledgeBundle = ${JSON.stringify(bundle, null, 2)};

export const CV_CATALOG = ${JSON.stringify(catalog)};
`;
  await mkdir(path.dirname(OUTPUT), { recursive: true });
  // Unchanged output isn't rewritten, so `wrangler dev`'s file watcher doesn't loop on its own build.
  const current = await readFile(OUTPUT, "utf8").catch(() => "");
  if (current !== source) await writeFile(OUTPUT, source, "utf8");
  const chars = bundle.text.en.length + bundle.text.ar.length;
  console.log(`Knowledge ${version} → ${path.relative(process.cwd(), OUTPUT)} (${bundle.anchors.length} anchors, ${bundle.evidence.length} evidence terms, ${chars.toLocaleString("en-US")} characters of text)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
